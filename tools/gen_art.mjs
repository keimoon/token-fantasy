// Generate src/art.rs and src/art.bin from the design's art (design/*.js),
// the single source of the pixels:
//   node tools/gen_art.mjs
// Every sprite becomes an indexed image with its own small RGB565 palette
// (index 0 = transparent), exactly as the design page rasters it: players
// per class, palette variant and pose, monsters per frame, the icons, the
// font, and the three battlefields (day, dusk, night) as indexed images too.
// The palettes and tables go to art.rs; every image's pixel indexes go, one
// after another, to art.bin, which art.rs includes.
import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
for (const f of ['common.js', 'art_players.js', 'art_monsters.js', 'engine.js']) require(path.join(here, '../design', f));
const FFC = globalThis.FFC, PL = globalThis.FF_PLAYERS, B = globalThis.FFB;

const hex4 = v => '0x' + v.toString(16).padStart(4, '0');
/* packed ABGR (FFC.pack) -> RGB565; the colours are already quantized */
const c565 = v => (((v & 255) >> 3) << 11) | ((((v >>> 8) & 255) >> 2) << 5) | (((v >>> 16) & 255) >> 3);
/* camelCase or snake -> UPPER_SNAKE */
const upper = s => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^A-Za-z0-9]/g, '_').toUpperCase();
const camel = s => s.replace(/(^|_)([a-z])/g, (_, __, c) => c.toUpperCase());

const R = [], bin = [];
let binLen = 0, imgCount = 0;

/* one indexed image: its pixels appended to art.bin, its palette inline */
function img(im) {
    const pal = [0], idx = new Map();
    const px = new Uint8Array(im.w * im.h);
    for (let i = 0; i < px.length; i++) {
        const v = im.px[i];
        if (!v) continue;
        const c = c565(v);
        if (!idx.has(c)) {
            if (pal.length === 256) throw new Error('more than 255 colours');
            idx.set(c, pal.length);
            pal.push(c);
        }
        px[i] = idx.get(c);
    }
    const off = binLen;
    bin.push(px);
    binLen += px.length;
    imgCount++;
    return `Img { w: ${im.w}, h: ${im.h}, pal: &[${pal.map(hex4).join(', ')}], off: ${off} }`;
}

R.push('//! Generated by tools/gen_art.mjs from the art in design/. Do not edit.', '');
R.push('/// An indexed image: pal[px] is the RGB565 colour, index 0 is transparent.');
R.push('#[derive(Clone, Copy, Debug)]');
R.push('pub struct Img {', '    pub w: u16,', '    pub h: u16,', '    pub pal: &\'static [u16],', '    off: u32,', '}', '');
R.push('static PX: &[u8] = include_bytes!("art.bin");', '');
R.push('impl Img {');
R.push('    /// Row-major palette indexes, w * h of them.');
R.push('    pub fn px(&self) -> &\'static [u8] {');
R.push('        &PX[self.off as usize..][..self.w as usize * self.h as usize]');
R.push('    }', '}', '');

/* ---- colours the engine names (design/engine.js COL) ---- */
R.push('/// The scene\'s named colours, RGB565.');
R.push('pub mod c {');
for (const [k, v] of Object.entries(B.COL)) R.push(`    pub const ${upper(k)}: u16 = ${hex4(c565(v))};`);
R.push('}', '');

/* ---- players ---- */
const POSES = Object.keys(PL.POSES);
R.push('/// Player poses, in this order in `Class::img`.');
R.push('#[derive(Clone, Copy, Debug, PartialEq, Eq)]');
R.push(`pub enum Pose { ${POSES.map(camel).join(', ')} }`);
R.push(`pub const POSES: usize = ${POSES.length};`);
R.push('/// An upright pose stands on (UP_AX, UP_AY) of its image; facing left.');
R.push(`pub const UP_AX: i32 = ${B.UP_AX};`, `pub const UP_AY: i32 = ${B.UP_AY};`, '');
const STRIKE = { sword: 'Slash', dagger: 'Slash2', rapier: 'Thrust', lance: 'Thrust', staffB: 'Bonk', staffW: 'Bonk', rod: 'Bonk' };
R.push('/// The hit a weapon (or fists) makes on an attack.');
R.push('#[derive(Clone, Copy, Debug, PartialEq, Eq)]');
R.push('pub enum Strike { Slash, Slash2, Thrust, Bonk, Flurry }', '');
R.push('pub struct Class {');
R.push('    pub id: &\'static str,');
R.push('    pub job: &\'static str,');
R.push('    /// Codex sessions are fighters, Claude Code ones mages.');
R.push('    pub fighter: bool,');
R.push('    pub strike: Strike,');
R.push('    /// The names a player of the class may be given.');
R.push('    pub names: &\'static [&\'static str],');
R.push('    /// [palette variant][pose]; variant 1 is the swap.');
R.push(`    pub img: [[Img; ${POSES.length}]; 2],`);
R.push('    /// Where the lying KO sprite touches the ground.');
R.push('    pub ko_ax: i32,', '    pub ko_ay: i32,', '}', '');
const classRows = [];
B.CLS.forEach(k => {
    const c = k.c;
    const imgs = [0, 1].map(v => POSES.map(pose => '            ' + img(k.variants[v][pose]) + ',').join('\n'));
    classRows.push(`    Class {\n        id: ${JSON.stringify(c.id)},\n        job: ${JSON.stringify(c.job)},\n` +
        `        fighter: ${c.kind === 'fighter'},\n        strike: Strike::${STRIKE[c.weapon] || 'Flurry'},\n` +
        `        names: &[${c.names.map(n => JSON.stringify(n)).join(', ')}],\n` +
        `        img: [\n          [\n${imgs[0]}\n          ],\n          [\n${imgs[1]}\n          ],\n        ],\n` +
        `        ko_ax: ${k.koA[0]},\n        ko_ay: ${k.koA[1]},\n    },`);
});
R.push(`pub static CLASSES: [Class; ${B.CLS.length}] = [`, ...classRows, '];', '');

/* ---- monsters ---- */
const FX = ['punch', 'blaze', 'needles', 'knife', 'doom', 'breath', 'blaster', 'meteor'];
R.push('/// The monsters\' attacks on an idle player.');
R.push('#[derive(Clone, Copy, Debug, PartialEq, Eq)]');
R.push(`pub enum MonFx { ${FX.map(camel).join(', ')} }`, '');
R.push('pub struct Monster {');
R.push('    pub name: &\'static str,', '    pub attack: &\'static str,', '    pub fx: MonFx,');
R.push('    /// Hovers and bobs.', '    pub floats: bool,');
R.push('    /// Facing right, standing on the bottom row.');
R.push('    pub idle: Img,', '    pub idle2: Img,', '    pub attack_img: Img,', '}', '');
const monRows = [];
for (const { m, f } of B.MONS) {
    if (!FX.includes(m.fx)) throw new Error(`${m.id}: unknown fx ${m.fx}`);
    const fr = k => img(f[k] || f.idle);
    monRows.push(`    Monster {\n        name: ${JSON.stringify(m.name)},\n        attack: ${JSON.stringify(m.attack)},\n` +
        `        fx: MonFx::${camel(m.fx)},\n        floats: ${!!m.float},\n        idle: ${fr('idle')},\n` +
        `        idle2: ${fr('idle2')},\n        attack_img: ${fr('attack')},\n    },`);
}
R.push(`pub static MONSTERS: [Monster; ${B.MONS.length}] = [`, ...monRows, '];', '');

/* ---- icons ---- */
R.push('// Small sprites: the tool logos, the hand cursor, the Phoenix Plume, the bubbles.');
for (const [k, im] of Object.entries(B.ICON)) {
    if (k === 'cursorL') continue;
    R.push(`pub const ICON_${upper(k)}: Img = ${img(im)};`);
}
R.push('');

/* ---- the battlefields ---- */
const TODS = Object.keys(B.TOD);
R.push('/// The time of day, which picks the battlefield.');
R.push('#[derive(Clone, Copy, Debug, PartialEq, Eq)]');
R.push(`pub enum Tod { ${TODS.map(camel).join(', ')} }`);
R.push('pub const FIELD_W: usize = 426;', 'pub const FIELD_H: usize = 176;');
R.push('/// The battlefield behind everything (FIELD_H rows), per time of day.');
const fields = TODS.map(t => '    ' + img({ w: 426, h: 176, px: B.makeField(t).slice(0, 426 * 176) }) + ',');
R.push(`pub static FIELDS: [Img; ${TODS.length}] = [`, ...fields, '];', '');

/* ---- font ---- */
R.push('/// 5x7 font: rows of 5 bits (bit 4 = left), for ASCII 32..127.');
const font = [], has = [];
for (let c = 32; c < 128; c++) {
    const g = FFC.GLYPH[String.fromCharCode(c)];
    has.push(g ? 'true' : 'false');
    font.push('    [' + (g ? g.map(r => '0x' + parseInt(r.replace(/#/g, '1').replace(/\./g, '0'), 2).toString(16).padStart(2, '0')) : Array(7).fill('0x00')).join(', ') + '],');
}
R.push('pub static FONT: [[u8; 7]; 96] = [', ...font, '];');
R.push('pub static FONT_HAS: [bool; 96] = [' + has.join(', ') + '];');

const out = Buffer.alloc(binLen);
let o = 0;
for (const px of bin) { out.set(px, o); o += px.length; }
fs.writeFileSync(path.join(here, '../src/art.bin'), out);
fs.writeFileSync(path.join(here, '../src/art.rs'), R.join('\n') + '\n');
console.log(`src/art.rs + src/art.bin: ${imgCount} images, ${(binLen / 1024).toFixed(0)} KB of pixels`);
