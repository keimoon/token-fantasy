'use strict';

function q(hex) {
    const v = parseInt(hex.slice(1), 16);
    const r = (v >> 19) & 31, g = (v >> 10) & 63, b = (v >> 3) & 31;
    return [(r << 3) | (r >> 2), (g << 2) | (g >> 4), (b << 3) | (b >> 2)];
}
function pack(rgb, a = 255) { return ((a << 24) | (rgb[2] << 16) | (rgb[1] << 8) | rgb[0]) >>> 0; }
function hexPx(hex) { return pack(q(hex)); }

/* Keys every sprite may use without declaring them. */
const BASE = {
    K: '#1a1222',   // outline
    W: '#f8f8f0',   // white
    w: '#aeb0c8',   // white shade
    Y: '#f8d850',   // gold
    y: '#b8861c',   // gold shade
    X: '#e83c3c',   // red
    x: '#8c1c28',   // red shade
    I: '#d8e0f0',   // steel
    i: '#8890b0',   // steel shade
    N: '#9a6a3a',   // wood
    n: '#5e3c22',   // wood shade
};

function sprite(name, rows, pal = {}) {
    const w = rows[0].length;
    rows.forEach((r, j) => {
        if (r.length !== w) throw new Error(`${name}: row ${j} is ${r.length} wide, expected ${w}: "${r}"`);
    });
    return { name, w, h: rows.length, rows, pal };
}

/* Rows -> packed pixels. With outline, the image grows by 1 px on each side
 * and every empty pixel that touches a filled one (4-neighbours) becomes K. */
function raster(sp, outline = true, palOver) {
    const pal = Object.assign({}, BASE, sp.pal, palOver || {});
    const o = outline ? 1 : 0, w = sp.w + 2 * o, h = sp.h + 2 * o;
    const px = new Uint32Array(w * h);
    for (let j = 0; j < sp.h; j++) for (let i = 0; i < sp.w; i++) {
        const ch = sp.rows[j][i];
        if (ch === '.') continue;
        const hex = pal[ch];
        if (!hex) throw new Error(`${sp.name}: no colour for '${ch}'`);
        px[(j + o) * w + i + o] = hexPx(hex);
    }
    if (outline) {
        const k = hexPx(pal.K), fill = px.slice();
        for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) {
            if (fill[j * w + i]) continue;
            if ((i > 0 && fill[j * w + i - 1]) || (i < w - 1 && fill[j * w + i + 1]) ||
                (j > 0 && fill[(j - 1) * w + i]) || (j < h - 1 && fill[(j + 1) * w + i])) px[j * w + i] = k;
        }
    }
    return { w, h, px };
}

function flipX(img) {
    const px = new Uint32Array(img.w * img.h);
    for (let j = 0; j < img.h; j++) for (let i = 0; i < img.w; i++) px[j * img.w + i] = img.px[j * img.w + img.w - 1 - i];
    return { w: img.w, h: img.h, px };
}

/* Quarter turn clockwise (a standing sprite lying down, head to the right). */
function rotCW(img) {
    const w = img.h, h = img.w, px = new Uint32Array(w * h);
    for (let j = 0; j < img.h; j++) for (let i = 0; i < img.w; i++) px[i * w + (img.h - 1 - j)] = img.px[j * img.w + i];
    return { w, h, px };
}
function rotCCW(img) {
    const w = img.h, h = img.w, px = new Uint32Array(w * h);
    for (let j = 0; j < img.h; j++) for (let i = 0; i < img.w; i++) px[(img.w - 1 - i) * w + j] = img.px[j * img.w + i];
    return { w, h, px };
}

